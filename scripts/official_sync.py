def sync_sources_md():
    with io.open(SOURCES, encoding='utf-8') as f:
        s = f.read()
    body = generated_sections()
    if BEG in s and END in s:
        head = s[:s.index(BEG)]
        tail = s[s.index(END) + len(END):]
    else:
        # أول تشغيل: نضع القسم المولَّد قبل «الثغرات المتبقية» إن وُجد
        anchor = '## الثغرات المتبقية'
        i = s.find(anchor)
        if i == -1:
            head, tail = s, ''
        else:
            head, tail = s[:i], s[i:]
    out = head + BEG + '\n\n' + body + '\n' + END + '\n\n---\n\n' + tail
    with io.open(SOURCES, 'w', encoding='utf-8') as f:
        f.write(out)


