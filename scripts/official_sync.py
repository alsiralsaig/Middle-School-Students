def _sync_syllabus(slug, units, ref, extra=None):
    """تكتب حقل syllabus القياسي في ملف المادة."""
    p = os.path.join(ROOT, 'shared/content/%s.json' % slug)
    d = load(p)
    d['curriculumRef'] = ref
    d['unitsCount'] = len(units)
    n_lessons = 0
    syll = []
    for u in units:
        n, title, page = u[0], u[1], u[2]
        obj = u[3] if len(u) > 3 and isinstance(u[3], list) and u[3] and isinstance(u[3][0], str) else []
        lessons = u[-1] if len(u) > 3 and isinstance(u[-1], list) and u[-1] and isinstance(u[-1][0], tuple) else []
        n_lessons += len(lessons)
        e = od([('unitNumber', n), ('title', title), ('sourceConfidence', 'high'),
                ('numbering', 'lessons')])
        if page is not None:
            e['sourcePage'] = page
        if obj:
            e['objectives'] = obj
        e['lessons'] = [od([('lessonNumber', ln), ('title', lt)] +
                           ([('sourcePage', lp)] if lp is not None else []))
                        for ln, lt, lp in lessons]
        syll.append(e)
    if n_lessons:
        d['lessonsCount'] = n_lessons
    d['syllabus'] = syll
    if extra:
        d.update(extra)
        o = d.get('official') or od()
        o.update(extra.get('officialPatch', {}))
        d['official'] = o
        d.pop('officialPatch', None)
    with io.open(p, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write('\n')
    return len(syll), n_lessons


